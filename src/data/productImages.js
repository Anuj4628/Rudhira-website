/**
 * Returns the exact verified image from the product's authentic folder
 * for the requested material.
 */
export function getProductMaterialImage(productSlug, materialSlug) {
  if (!productSlug) return null;
  const cleanProd = productSlug.toLowerCase().trim();
  const cleanMat = materialSlug ? materialSlug.toLowerCase().trim() : 'stainless-steel';

  const productMap = PRODUCT_MATERIAL_IMAGES[cleanProd];
  if (productMap && productMap[cleanMat]) {
    return productMap[cleanMat];
  }
  // Graceful fallback to stainless steel of that specific product
  if (productMap && productMap['stainless-steel']) {
    return productMap['stainless-steel'];
  }
  return null;
}

