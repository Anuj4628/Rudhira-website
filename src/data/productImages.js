/**
 * Returns material-specific type image for flanges or fasteners.
 */
export function getTypeMaterialImage(productSlug, typeSlug, materialSlug) {
  const cleanProd = (productSlug || '').toLowerCase().trim();
  const cleanType = (typeSlug || '').toLowerCase().trim();
  const cleanMat = (materialSlug || 'stainless-steel').toLowerCase().trim();

  if (cleanProd === 'flanges') {
    const matMap = FLANGE_TYPES_BY_MATERIAL[cleanMat] || FLANGE_TYPES_BY_MATERIAL['stainless-steel'];
    if (matMap && matMap[cleanType]) return matMap[cleanType];
    return FLANGE_TYPES_BY_MATERIAL['stainless-steel'][cleanType] || null;
  }

  if (cleanProd === 'fasteners') {
    const matMap = FASTENER_TYPES_BY_MATERIAL[cleanMat] || FASTENER_TYPES_BY_MATERIAL['stainless-steel'];
    if (matMap && matMap[cleanType]) return matMap[cleanType];
    return FASTENER_TYPES_BY_MATERIAL['stainless-steel'][cleanType] || null;
  }

  return null;
}
